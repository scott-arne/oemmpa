"""Single-cut stereochemistry parity against a committed mmpdb oracle.

The oracle ``tests/data/mmpdb/stereo_fragmentations.tsv`` was generated by
mmpdb 3.1.4 from ``tests/data/mmpdb/stereo_cases.smi`` with ``--num-cuts 1``
(the exact command is recorded in ``tests/parity/fixtures.tsv``).  Comparing a
committed table rather than calling mmpdb at test time keeps the suite free of
an mmpdb install while still pinning OEMMPA to upstream behaviour.

The comparison is not an identity.  mmpdb writes bare ``*`` attachment points
and OEMMPA writes ``[*:1]``, and the two toolkits order SMILES differently, so
both sides are projected through RDKit canonicalisation before the row sets are
compared.  The projection also collapses mmpdb's three enumeration labels
(``N``/``C``/``V``) onto OEMMPA's two-valued distinction between a baseline
record and an up-enumerated one, because mmpdb's split of enumerated records
into "constant up" and "variable up" is an artefact of which fragment its
single-cut loop happened to read.

Hydrogen fragmentations are absent from the oracle by construction.  The
``mmpdb fragment`` command drives :func:`mmpdblib.fragment_algorithm.fragment_mol`,
which never emits ``[*][H]`` records; ``get_hydrogen_fragmentations`` -- the sole
producer of mmpdb's ``_hydrogen_cut_smiles`` constant -- is reachable only from
the transform and predict commands.  That is an intentional upstream design
difference rather than a gap in this fixture, and
:func:`test_oracle_contains_no_hydrogen_cut_rows` pins it so the absence cannot
drift into an unnoticed loss of coverage.  The pin is structural: a fragment
whose projected molecule has no heavy atoms is a hydrogen fragment whatever
spelling upstream chooses for it.

Differences that remain after projection are governed by
``tests/data/mmpdb/stereo_expected_differences.tsv``.  Three rules apply:

* every observed difference must have an allowlist row,
* every allowlist row must correspond to an observed difference, and
* a difference in a baseline record is never allowlistable -- baseline parity
  is unconditional, and only up-enumerated records may diverge, and then only
  where the divergence is attributable to one of the four mmpdb reference
  defects that OEMMPA deliberately does not replicate.

The enforcement helpers take the difference list and the allowlist rows as
arguments so the guards themselves can be exercised against synthetic in-memory
rows without touching the committed fixture.  Differences are carried as full
records, enumeration label included, and are reduced to the allowlist identity
only inside the two allowlist checks: reducing earlier let one difference
overwrite another that shared an identity, which could hide a baseline
divergence behind an allowlisted enumerated one.
"""

import csv
import re
from contextlib import contextmanager
from pathlib import Path

import pytest
from mmpdb_surplus_classifier import _canonical_smiles
from oemmpa.oemmpa import Fragmentation, Fragmenter
from openeye import oechem
from rdkit import Chem, RDLogger

DATA_DIR = Path(__file__).resolve().parents[1] / "data" / "mmpdb"
CASES_PATH = DATA_DIR / "stereo_cases.smi"
ORACLE_PATH = DATA_DIR / "stereo_fragmentations.tsv"
ALLOWLIST_PATH = DATA_DIR / "stereo_expected_differences.tsv"

ORACLE_COLUMNS = [
    "molecule_id",
    "num_cuts",
    "enumeration_label",
    "variable_num_heavies",
    "variable_smiles",
    "attachment_order",
    "constant_num_heavies",
    "constant_smiles",
    "constant_with_h_smiles",
]
ALLOWLIST_COLUMNS = [
    "molecule_id",
    "direction",
    "variable_smiles",
    "constant_smiles",
    "defect",
    "rationale",
]

BASELINE = "baseline"
ENUMERATED = "enumerated"

# mmpdb labels an up-enumerated record by the fragment it walked ("C" for the
# constant side, "V" for the variable side).  OEMMPA records only whether the
# record was enumerated, so both map onto the same value here.
MMPDB_LABELS = {"N": BASELINE, "C": ENUMERATED, "V": ENUMERATED}

OEMMPA_SURPLUS = "oemmpa-surplus"
MMPDB_SURPLUS = "mmpdb-surplus"
VALID_DIRECTIONS = {OEMMPA_SURPLUS, MMPDB_SURPLUS}

# The four mmpdb reference defects OEMMPA deliberately does not replicate; only
# these may justify an allowlist row.
VALID_DEFECTS = {"1", "2", "3", "4"}

# mmpdblib.fragment_algorithm._hydrogen_cut_smiles.
MMPDB_HYDROGEN_CUT_SMILES = "[*][H]"


@contextmanager
def _rdkit_warnings_silenced():
    """Suppress RDKit's parse warnings for the duration of the block.

    RDKit's logger is process-global, so disabling it without restoring it
    would strip warnings from every test that ran afterwards and make the suite
    order-dependent.  Re-enabling in a ``finally`` keeps the suppression scoped
    to the caller even when the body fails.
    """
    RDLogger.DisableLog("rdApp.warning")  # type: ignore[attr-defined]  # pyright: ignore[reportAttributeAccessIssue]
    try:
        yield
    finally:
        RDLogger.EnableLog("rdApp.warning")  # type: ignore[attr-defined]  # pyright: ignore[reportAttributeAccessIssue]


def _enumeration_label_none():
    """Return the integer SWIG uses for ``EnumerationLabel::None``.

    SWIG 4.5.1 flattens ``enum class`` into plain integers exposed as class
    attributes on :class:`Fragmentation`, so the constant is discovered by name
    rather than imported.

    :returns: The integer value of the ``None`` enumeration label.
    :raises AttributeError: When no matching attribute is exposed.
    """
    for name, value in vars(Fragmentation).items():
        if name.endswith("EnumerationLabel__None") and isinstance(value, int):
            return value
    raise AttributeError("Fragmentation exposes no EnumerationLabel__None constant")


ENUMERATION_LABEL_NONE = _enumeration_label_none()


def _project(smiles):
    """Project an mmpdb or OEMMPA fragment SMILES onto the comparison form.

    mmpdb writes bare ``*`` attachment points, and a bracketed ``[*]`` where the
    dummy needs brackets (a metal neighbour, or its hydrogen-cut constant);
    OEMMPA writes ``[*:1]``.  Unbracketing first means the middle replacement
    covers both mmpdb spellings, and the last replacement undoes the damage that
    replacement does to already mapped OEMMPA input.  The result is idempotent,
    so both sides share one code path.

    :param smiles: A fragment SMILES from either toolkit.
    :returns: The RDKit-canonical form with mapped attachment points.
    :raises AssertionError: When the projected SMILES does not parse.
    """
    mapped = (
        smiles.replace("[*]", "*").replace("*", "[*:1]").replace("[[*:1]:1]", "[*:1]")
    )
    assert Chem.MolFromSmiles(mapped) is not None, (
        f"projection of {smiles!r} produced unparsable SMILES {mapped!r}"
    )
    return _canonical_smiles(mapped)


def _heavy_atoms(projected):
    """Return the RDKit heavy-atom count of an already projected SMILES."""
    mol = Chem.MolFromSmiles(projected)
    assert mol is not None, projected
    return mol.GetNumHeavyAtoms()


def _is_hydrogen_fragment(projected):
    """Return whether a projected fragment carries no heavy atom.

    A real variable or constant fragment always has at least one heavy atom, so
    a heavy-atom count of zero identifies mmpdb's hydrogen cut regardless of how
    upstream spells the dummy.
    """
    return _heavy_atoms(projected) == 0


def _record(variable_smiles, constant_smiles, label):
    variable = _project(variable_smiles)
    constant = _project(constant_smiles)
    return (
        variable,
        constant,
        _heavy_atoms(variable),
        _heavy_atoms(constant),
        label,
    )


def _read_cases():
    """Return the fixture as a list of ``(title, smiles)`` pairs in file order."""
    cases = []
    for line in CASES_PATH.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        smiles, title = line.split("\t")
        cases.append((title, smiles))
    return cases


def _read_oracle_rows(path=None):
    with (path or ORACLE_PATH).open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        assert reader.fieldnames == ORACLE_COLUMNS
        return list(reader)


def _hydrogen_oracle_rows(rows):
    """Return the subset of oracle rows that describe a hydrogen fragmentation."""
    return [
        row
        for row in rows
        if _is_hydrogen_fragment(_project(row["variable_smiles"]))
        or _is_hydrogen_fragment(_project(row["constant_smiles"]))
    ]


def _assert_no_duplicate_records(records, context):
    """Fail when a raw record list holds the same record twice.

    Both sides are compared as sets, so a regression that emitted a record
    twice -- the same constant, variable and enumeration label at the same cut
    count -- would be absorbed by the set and never surface as a difference.
    The raw lists are therefore checked before either is normalised.

    :param records: The records in emission order, before set conversion.
    :param context: What produced them, named in the failure message.
    :raises AssertionError: When any record appears more than once.
    """
    assert len(records) == len(set(records)), (
        f"{context} emitted duplicate records: "
        f"{sorted({record for record in records if records.count(record) > 1})}"
    )


def _load_oracle():
    """Return ``{title: set of projected records}`` from the committed oracle."""
    rows_by_title = {}
    for row in _read_oracle_rows():
        assert row["num_cuts"] == "1", row
        assert row["attachment_order"] == "0", row
        record = _record(
            row["variable_smiles"],
            row["constant_smiles"],
            MMPDB_LABELS[row["enumeration_label"]],
        )
        # Projection rule 4: the recomputed heavy counts must agree with the
        # counts mmpdb stored, or the projection has silently changed the graph.
        assert record[2] == int(row["variable_num_heavies"]), row
        assert record[3] == int(row["constant_num_heavies"]), row
        rows_by_title.setdefault(row["molecule_id"], []).append(record)

    oracle = {}
    for title, records in rows_by_title.items():
        _assert_no_duplicate_records(records, f"the oracle for {title}")
        oracle[title] = set(records)
    return oracle


def _oemmpa_rows(smiles):
    """Return the projected single-cut record set OEMMPA produces for ``smiles``."""
    mol = oechem.OEGraphMol()
    assert oechem.OESmilesToMol(mol, smiles), smiles
    fragmenter = Fragmenter()
    fragmenter.SetMaxCuts(1)
    records = []
    for fragmentation in fragmenter.Fragment(1, mol):
        assert fragmentation.GetCutCount() == 1, smiles
        label = (
            BASELINE
            if fragmentation.GetEnumerationLabel() == ENUMERATION_LABEL_NONE
            else ENUMERATED
        )
        records.append(
            _record(
                fragmentation.GetVariableSmiles(),
                fragmentation.GetConstantSmiles(),
                label,
            )
        )
    _assert_no_duplicate_records(records, f"the fragmenter for {smiles}")
    return set(records)


def _load_allowlist():
    with ALLOWLIST_PATH.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        assert reader.fieldnames == ALLOWLIST_COLUMNS
        return list(reader)


def _allowlist_key(row):
    """Return the difference key an allowlist row refers to.

    The SMILES columns go through the same projection as the compared records,
    so a row transcribed from raw mmpdb output or from any other valid rendering
    still matches instead of reading as stale.
    """
    return (
        row["molecule_id"],
        row["direction"],
        _project(row["variable_smiles"]),
        _project(row["constant_smiles"]),
    )


def _difference_key(entry):
    """Return the allowlist identity of a full difference entry."""
    title, direction, record = entry
    return (title, direction, record[0], record[1])


def _keyed_differences(differences):
    """Group full difference entries by allowlist identity.

    Two entries can share an identity and differ only in enumeration label, so
    the grouping keeps every entry.  A plain ``{key: entry}`` mapping would drop
    one of them in set-iteration order, and an allowlist row for that identity
    would then excuse a baseline divergence that had been overwritten.

    :param differences: Full ``(molecule_id, direction, record)`` entries.
    :returns: A mapping from allowlist identity to the list of entries.
    """
    keyed = {}
    for entry in differences:
        keyed.setdefault(_difference_key(entry), []).append(entry)
    return keyed


def _baseline_differences(differences):
    """Return the identities of every difference in a baseline record."""
    return sorted(
        _difference_key(entry) + (entry[2][4],)
        for entry in differences
        if entry[2][4] == BASELINE
    )


def _unexplained_differences(differences, allowlist_rows):
    """Return the difference identities no allowlist row accounts for."""
    allowed = {_allowlist_key(row) for row in allowlist_rows}
    return sorted(key for key in _keyed_differences(differences) if key not in allowed)


def _stale_allowlist_rows(differences, allowlist_rows):
    """Return the keys of allowlist rows that describe no observed difference.

    :raises AssertionError: When a row is malformed, or when it accepts a
        baseline record -- baseline parity is unconditional.
    """
    keyed = _keyed_differences(differences)
    stale = []
    for row in allowlist_rows:
        assert row["direction"] in VALID_DIRECTIONS, row
        assert row["defect"] in VALID_DEFECTS, row
        assert row["rationale"].strip(), row
        key = _allowlist_key(row)
        matched = keyed.get(key, [])
        if not matched:
            stale.append(key)
        else:
            # A baseline divergence is a defect in OEMMPA, never an accepted
            # one, and an enumerated entry does not excuse a baseline entry
            # that happens to share its identity.
            assert all(entry[2][4] == ENUMERATED for entry in matched), row
    return stale


def _differences():
    """Return every projected record present on exactly one side.

    :returns: A list of ``(molecule_id, direction, record)`` entries covering
        both directions.  The full record is kept, enumeration label included,
        so nothing is reduced to the allowlist identity before the baseline
        gate has seen it.
    """
    oracle = _load_oracle()
    differences = []
    for title, smiles in _read_cases():
        expected = oracle.get(title, set())
        observed = _oemmpa_rows(smiles)
        for direction, records in (
            (OEMMPA_SURPLUS, observed - expected),
            (MMPDB_SURPLUS, expected - observed),
        ):
            differences.extend((title, direction, record) for record in sorted(records))
    return differences


@pytest.fixture(scope="module")
def differences():
    with _rdkit_warnings_silenced():
        return _differences()


def test_oracle_covers_every_fixture_structure():
    with _rdkit_warnings_silenced():
        oracle = _load_oracle()
    titles = [title for title, _ in _read_cases()]

    assert len(titles) == len(set(titles))
    assert set(titles) == set(oracle)
    for title in titles:
        assert oracle[title], title


def test_oracle_contains_no_hydrogen_cut_rows():
    """``mmpdb fragment`` never emits hydrogen fragmentations for single cuts.

    ``fragment_mol`` does not call ``get_hydrogen_fragmentations``; only the
    transform and predict commands do.  Pinning the absence keeps the oracle
    honest about what it does and does not cover.
    """
    with _rdkit_warnings_silenced():
        rows = _read_oracle_rows()

        assert rows
        # The structural test must actually recognise upstream's spelling.
        assert _is_hydrogen_fragment(_project(MMPDB_HYDROGEN_CUT_SMILES))
        assert _hydrogen_oracle_rows(rows) == []


def test_no_baseline_record_differs(differences):
    """Baseline parity is unconditional and cannot be allowlisted.

    The gate reads the full difference entries rather than the allowlist
    identities, so it sees a baseline divergence even when another difference
    shares that identity.
    """
    assert _baseline_differences(differences) == []


def test_every_difference_is_allowlisted(differences):
    assert _unexplained_differences(differences, _load_allowlist()) == []


def test_no_allowlist_row_is_stale(differences):
    assert _stale_allowlist_rows(differences, _load_allowlist()) == []


# --- Guards on the guards -------------------------------------------------
#
# The committed allowlist is empty, so the three enforcement rules above are
# never exercised by real data.  These checks run them against synthetic rows
# held in memory; they touch no fixture.

SYNTHETIC_ID = "synthetic_case"
SYNTHETIC_VARIABLE = "C[*:1]"
SYNTHETIC_CONSTANT = "OC[*:1]"


def _synthetic_differences(*labels):
    """Return one synthetic OEMMPA-surplus difference entry per label.

    Every entry carries the same variable and constant, so passing more than
    one label produces entries that collide on the allowlist identity.
    """
    return [
        (
            SYNTHETIC_ID,
            OEMMPA_SURPLUS,
            _record(SYNTHETIC_VARIABLE, SYNTHETIC_CONSTANT, label),
        )
        for label in labels
    ]


def _synthetic_allowlist_row(**overrides):
    row = {
        "molecule_id": SYNTHETIC_ID,
        "direction": OEMMPA_SURPLUS,
        # Deliberately not the canonical rendering, to prove the key is
        # projected rather than compared literally.
        "variable_smiles": "[*:1]C",
        "constant_smiles": "[*:1]CO",
        "defect": "2",
        "rationale": "synthetic probe",
    }
    row.update(overrides)
    return row


@pytest.mark.parametrize(
    "label,overrides",
    [(BASELINE, {"defect": defect}) for defect in sorted(VALID_DEFECTS)]
    + [
        (ENUMERATED, {"direction": "sideways"}),
        (ENUMERATED, {"direction": ""}),
        (ENUMERATED, {"defect": "5"}),
        (ENUMERATED, {"defect": ""}),
        (ENUMERATED, {"rationale": ""}),
        (ENUMERATED, {"rationale": "   "}),
    ],
)
def test_allowlist_guard_rejects_invalid_rows(label, overrides):
    with _rdkit_warnings_silenced():
        differences = _synthetic_differences(label)

        with pytest.raises(AssertionError):
            _stale_allowlist_rows(differences, [_synthetic_allowlist_row(**overrides)])


def test_allowlist_guard_reports_stale_rows():
    with _rdkit_warnings_silenced():
        row = _synthetic_allowlist_row()

        assert _stale_allowlist_rows([], [row]) == [_allowlist_key(row)]


def test_allowlist_guard_reports_unlisted_differences():
    with _rdkit_warnings_silenced():
        differences = _synthetic_differences(ENUMERATED)
        rows = [_synthetic_allowlist_row()]

        assert _unexplained_differences(differences, []) == [
            _difference_key(entry) for entry in differences
        ]
        # The same difference, once allowlisted through a non-canonical
        # rendering, is neither unexplained nor stale.
        assert _unexplained_differences(differences, rows) == []
        assert _stale_allowlist_rows(differences, rows) == []


def test_baseline_gate_survives_an_identity_collision():
    """A baseline entry stays visible when another entry shares its identity.

    Reducing the differences to ``(molecule_id, direction, variable,
    constant)`` before the baseline gate ran let one entry overwrite the other
    in set-iteration order; an allowlist row for that identity then made the
    unconditional baseline check pass.  Real fragmenter output cannot produce
    the collision, because both sides deduplicate per key, so the guard is
    pinned against synthetic entries here.
    """
    with _rdkit_warnings_silenced():
        differences = _synthetic_differences(ENUMERATED, BASELINE)
        rows = [_synthetic_allowlist_row()]

        assert len({_difference_key(entry) for entry in differences}) == 1

        # Both orderings, because the defect was an ordering artefact.
        for ordering in (differences, differences[::-1]):
            assert len(_baseline_differences(ordering)) == 1
            assert _unexplained_differences(ordering, rows) == []
            with pytest.raises(AssertionError):
                _stale_allowlist_rows(ordering, rows)


def test_duplicate_record_guard_names_the_repeated_record():
    """A record emitted twice is caught before the set comparison hides it."""
    with _rdkit_warnings_silenced():
        record = _record(SYNTHETIC_VARIABLE, SYNTHETIC_CONSTANT, ENUMERATED)

        _assert_no_duplicate_records([record], "probe")
        with pytest.raises(AssertionError, match=re.escape(repr(record))):
            _assert_no_duplicate_records([record, record], "probe")
